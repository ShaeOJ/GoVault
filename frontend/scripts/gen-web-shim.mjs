// Generates src/web-shim/App.js from the Wails-generated bindings so the web
// build's method list stays in sync with the desktop bindings. Each bound method
// becomes an RPC call. Re-run after adding/removing bound App methods:
//   node scripts/gen-web-shim.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const src = readFileSync(join(here, '../wailsjs/go/appcore/App.js'), 'utf8');

const names = [...src.matchAll(/^export function (\w+)\(/gm)].map((m) => m[1]);
names.sort();

const out = [
  '// AUTO-GENERATED by scripts/gen-web-shim.mjs — do not edit.',
  '// Mirrors the bound appcore.App methods as RPC calls for the web build.',
  "import { rpc } from './rpc.js';",
  '',
  ...names.map((n) => `export function ${n}(...args) { return rpc('${n}', args); }`),
  '',
].join('\n');

writeFileSync(join(here, '../src/web-shim/App.js'), out);
console.log(`generated src/web-shim/App.js with ${names.length} methods`);
